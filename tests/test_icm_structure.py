"""Structural guardrails for the ICM layout.

These tests do not exercise application logic. They keep the repository's organization,
skill registry, and routing contract from drifting.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def test_layer_one_map_exists():
    agents = ROOT / "AGENTS.md"
    assert agents.is_file()
    text = agents.read_text(encoding="utf-8")
    assert "## Workspaces" in text
    assert "## Routing" in text
    assert "## NEVER" in text
    assert "skills-orchestrator" in text


def test_engineering_pipeline_exists():
    pipeline = ROOT / "CODE_PIPELINE.md"
    assert pipeline.is_file()
    text = pipeline.read_text(encoding="utf-8")
    for step in range(1, 10):
        assert f"## {step}." in text


def test_every_workspace_has_a_context_contract():
    for workspace in ("src", "ops", "data", "planning", "docs", "tests"):
        context = ROOT / workspace / "CONTEXT.md"
        assert context.is_file(), f"{workspace}/CONTEXT.md is missing"
        text = context.read_text(encoding="utf-8")
        for section in (
            "## 1. Role & Purpose",
            "## 2. Allowed Inputs",
            "## 3. Core Process & Execution",
            "## 4. Expected Outputs",
            "## 5. Local Invariants & NEVER Rules",
            "## 6. General Guidelines",
        ):
            assert section in text, f"{workspace}/CONTEXT.md is missing {section}"


def test_skills_source_of_truth_and_routing_authority():
    skills_dir = ROOT / ".agents" / "skills"
    assert skills_dir.is_dir()
    installed = {path.name for path in skills_dir.iterdir() if path.is_dir()}
    assert len(installed) >= 40
    for required in (
        "skills-orchestrator",
        "skills-route",
        "test-driven-development",
        "systematic-debugging",
        "transparent-data-masker",
        "verification-before-completion",
        "project-checkpoint",
        "icm-maintenance",
    ):
        assert required in installed
        assert (skills_dir / required / "SKILL.md").is_file()

    route = (skills_dir / "skills-route" / "SKILL.md").read_text(encoding="utf-8")
    for category in range(1, 8):
        assert f"Category {category}" in route


def test_skill_registry_lists_every_installed_skill():
    registry = (ROOT / "docs" / "CUSTOM_SKILLS.md").read_text(encoding="utf-8")
    installed = {
        path.name
        for path in (ROOT / ".agents" / "skills").iterdir()
        if path.is_dir() and (path / "SKILL.md").is_file()
    }
    missing = sorted(name for name in installed if name not in registry)
    assert not missing, f"Skills missing from docs/CUSTOM_SKILLS.md: {missing}"


def test_cross_agent_artifacts_exist():
    assert (ROOT / ".claude" / "output-styles" / "bluf.md").is_file()
    settings = (ROOT / ".claude" / "settings.json").read_text(encoding="utf-8")
    assert '"outputStyle": "BLUF"' in settings
    rules = ROOT / ".agents" / "rules"
    assert (rules / "context-health.md").is_file()
    assert (rules / "graphify.md").is_file()


def test_generated_structure_doc_exists():
    structure = ROOT / "docs" / "structure.md"
    assert structure.is_file()
    text = structure.read_text(encoding="utf-8")
    assert "Repository Structure" in text
    assert "Generated by `ops/sync_tree.py`" in text


def test_python_package_layout_is_testable():
    assert (ROOT / "pytest.ini").is_file()
    assert (ROOT / "tests" / "CONTEXT.md").is_file()
    assert not (ROOT / "src" / "tests").exists(), "tests must live at the repo root"
