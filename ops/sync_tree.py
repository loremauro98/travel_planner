"""Regenerate docs/structure.md from the live repository tree.

Run from anywhere:
    C:\\Users\\lorem\\miniconda3\\envs\\travel\\python.exe ops\\sync_tree.py

This is the tree-sync dependency of the ``icm-maintenance`` skill.
"""

from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "structure.md"

IGNORED_DIRS = {
    ".git",
    ".claude",
    ".agents",
    ".venv",
    "venv",
    "env",
    "__pycache__",
    ".pytest_cache",
    ".ruff_cache",
    ".serena",
    "graphify-out",
    "current_output",
    ".ipynb_checkpoints",
    "node_modules",
    "dist",
    "build",
}

IGNORED_FILES = {
    ".env",
    "Thumbs.db",
    ".DS_Store",
}

IGNORED_SUFFIXES = {".pyc", ".pyo", ".db", ".sqlite", ".sqlite3", ".pkl", ".pickle"}


def _visible_children(directory: Path):
    children = []
    for child in sorted(
        directory.iterdir(), key=lambda item: (item.is_file(), item.name.lower())
    ):
        if child.name in IGNORED_FILES:
            continue
        if child.is_dir() and child.name in IGNORED_DIRS:
            continue
        if child.is_file() and child.suffix.lower() in IGNORED_SUFFIXES:
            continue
        children.append(child)
    return children


def _render_tree(directory: Path, prefix: str = "") -> list[str]:
    lines = []
    children = _visible_children(directory)
    for index, child in enumerate(children):
        is_last = index == len(children) - 1
        connector = "└── " if is_last else "├── "
        suffix = "/" if child.is_dir() else ""
        lines.append(f"{prefix}{connector}{child.name}{suffix}")
        if child.is_dir():
            extension = "    " if is_last else "│   "
            lines.extend(_render_tree(child, prefix + extension))
    return lines


def build_structure() -> str:
    tree_lines = [f"{ROOT.name}/", *_render_tree(ROOT)]
    workspace_rows = [
        ("`planning/`", "Specs, decisions, active task logs, archive"),
        ("`src/`", "Pure services and database access"),
        ("`data/`", "Append-only SQLite price store (gitignored)"),
        ("`ops/`", "Ingestion runners, notebooks, maintenance scripts"),
        ("`tests/`", "Headless pytest suites"),
        ("`docs/`", "Documentation, skill registry, changelog, reference notes"),
    ]
    rows = "\n".join(f"| {path} | {purpose} |" for path, purpose in workspace_rows)
    return (
        "# Repository Structure\n\n"
        "> Generated by `ops/sync_tree.py`. Do not edit by hand.\n"
        f"> Last generated: {date.today().isoformat()}\n\n"
        "## Tree\n\n"
        "```text\n" + "\n".join(tree_lines) + "\n```\n\n"
        "## Workspace contracts\n\n"
        "| Path | Purpose |\n|---|---|\n"
        f"{rows}\n\n"
        "## Skills\n\n"
        "The skill source of truth is `.agents/skills/`; the catalogue is\n"
        "[`CUSTOM_SKILLS.md`](CUSTOM_SKILLS.md). The `.claude/skills/` junction is gitignored and must\n"
        "be recreated after a fresh clone.\n"
    )


if __name__ == "__main__":
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(build_structure(), encoding="utf-8")
    print(f"Wrote {OUTPUT}")
